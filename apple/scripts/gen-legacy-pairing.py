#!/usr/bin/env python3
"""Write LoftCore's legacy pairing (0.1.x -> 0.2 migration) from our private ops files.

    apple/scripts/gen-legacy-pairing.py [ops-dir]      (default: ops/incremental)
    apple/scripts/gen-legacy-pairing.py --remove       (back to a public build)

Reads, from the ops dir (private; never in the public repo):
  gateway.toml      gateway_name, lan_url, public_url, public_mode  (what `pair` hands out)
  client-pins.txt   the direct-key pins 0.1.x had built in, one per line (# comments ok)

Writes apple/Packages/LoftCore/Sources/LoftCore/LegacyPairing+Ops.swift (gitignored), which
makes LegacyPairing.pairing return that gateway. Without the file a build has nothing to
migrate. Our private build scripts run this when ops/incremental exists.
Prints no address or pin, only what it included. Python 3.9+ (Xcode's), stdlib only.
"""
import base64
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "apple/Packages/LoftCore/Sources/LoftCore/LegacyPairing+Ops.swift"


def toml_strings(text: str) -> dict:
    """Top-level `key = "value"` lines (before the first [table]); enough for these keys."""
    out = {}
    for line in text.splitlines():
        if line.lstrip().startswith("["):
            break
        m = re.match(r'\s*([A-Za-z_]+)\s*=\s*"([^"]*)"', line)
        if m:
            out[m.group(1)] = m.group(2)
    return out


def main(argv):
    if argv[1:2] == ["--remove"]:
        OUT.unlink(missing_ok=True)
        print("LEGACY_PAIRING none (removed)")
        return 0
    ops = Path(argv[1]) if len(argv) > 1 else ROOT / "ops/incremental"
    cfg = toml_strings((ops / "gateway.toml").read_text())
    pins = [p.split("#")[0].strip() for p in (ops / "client-pins.txt").read_text().splitlines()]
    pins = [p for p in pins if p]
    for k in ("gateway_name", "lan_url"):
        if not cfg.get(k):
            sys.exit(f"FAILED: {k} missing in {ops}/gateway.toml")
    if not cfg["lan_url"].startswith("https://"):
        sys.exit("FAILED: lan_url is not https")
    if not pins or any(len(base64.b64decode(p + "=" * (-len(p) % 4))) != 32 for p in pins):
        sys.exit(f"FAILED: {ops}/client-pins.txt needs base64 SHA-256 pins")
    p = {"v": 1, "name": cfg["gateway_name"], "lan": cfg["lan_url"].rstrip("/"), "pins": pins}
    mode = cfg.get("public_mode", "none")
    if mode != "none":
        if mode not in ("tunnel", "direct") or not cfg.get("public_url", "").startswith("https://"):
            sys.exit("FAILED: public_mode/public_url in gateway.toml")
        p["pub"], p["mode"] = cfg["public_url"].rstrip("/"), mode
    raw = json.dumps(p, separators=(",", ":"), ensure_ascii=False).encode()
    payload = base64.urlsafe_b64encode(raw).rstrip(b"=").decode()
    OUT.write_text(
        "// GENERATED by apple/scripts/gen-legacy-pairing.py from ops/incremental. PRIVATE:\n"
        "// gitignored, never in the public repo. 0.1.x devices migrate to this gateway.\n"
        "extension LegacyPairing: LegacyPairingSource {\n"
        f'    public static let legacyPayload = "{payload}"\n'
        "}\n")
    print(f"LEGACY_PAIRING included: {len(pins)} pins, public route {mode}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
